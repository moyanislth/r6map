def normalize(en: str) -> str:
    s = re.sub(r"<br\s*/?>", " ", en)
    s = re.sub(r"\s+", " ", s).strip()
    return TYPO.get(s, s)


def main():
    n_with, n_without, n_total = 0, 0, 0
    for f in sorted(OUT.glob("*.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        for floor, items in data.items():
            for it in items:
                n_total += 1
                en = normalize(it["en"])
                it["en"] = en
                zh = ZH.get(en)
                if zh:
                    it["zh"] = zh
                    n_with += 1
                else:
                    n_without += 1
                    print(f"  未翻译: {f.stem}/{floor}: {en}")
        f.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\n共 {n_total} 条:中文 {n_with} 条,未翻译 {n_without} 条")


if __name__ == "__main__":
    main()
